"""Write a submission CSV from a registered method and validate it.

    python scripts/make_submission.py baseline50_dead
    python scripts/make_submission.py baseline50_dead --out submissions/try1.csv

Default output: evaluation/results/<method>.csv, where run_evaluation.py picks it up. That folder
is gitignored for our own files: a submission is regenerated by this command, never committed.
"""

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from mtah.data import load  # noqa: E402
from baseline import write_submission  # noqa: E402
from mtah.methods import METHODS  # noqa: E402

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("method", choices=sorted(METHODS))
    parser.add_argument("--out", help="output CSV (default evaluation/results/<method>.csv)")
    args = parser.parse_args()

    path = args.out or os.path.join(ROOT, "evaluation", "results", args.method + ".csv")
    labels = METHODS[args.method](load(mmap=False))
    write_submission(path, labels)
    print("wrote {}".format(os.path.relpath(path, ROOT)))
    sys.exit(subprocess.call([sys.executable, os.path.join(ROOT, "evaluation",
                                                           "validate_submission.py"), path]))
